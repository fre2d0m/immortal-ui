import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const output = new URL('.', import.meta.url).pathname;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1200 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(8000);
const base = 'http://127.0.0.1:4177/#/blocks/data-workflow';
const errors = [], checks = [], measurements = {};
page.on('pageerror', error => errors.push(error.message));
const button = name => page.getByRole('button', { name, exact: true });
const tooltip = page.locator('.wf-tooltip');
const toolSelector = '.wf-actions button,.wf-canvas-toolbar button,.wf-zoom-controls button';
const theme = async (mode, fontSize = 14) => {
  await page.evaluate(async ({ mode, fontSize }) => {
    const { applySettings } = await import('/src/lib/theme-storage.ts');
    const { defaultSettings } = await import('/src/lib/theme-settings.ts');
    applySettings({ ...defaultSettings, mode, fontSize });
  }, { mode, fontSize });
};
try {
  await page.goto(base);
  await page.locator('.wf-node').first().waitFor();
  for (const mode of ['dark', 'light']) {
    await theme(mode);
    measurements[mode] = await page.locator(toolSelector).evaluateAll(buttons => buttons.map(b => ({ name: b.ariaLabel, text: b.innerText, width: b.getBoundingClientRect().width, height: b.getBoundingClientRect().height })));
    assert.equal(measurements[mode].length, 11);
    assert.ok(measurements[mode].every(b => b.name && !b.text && b.width === 34 && b.height === 34));
    await page.locator('.wf-root').screenshot({ path: output + `overview-${mode}.png` });
    await page.mouse.move(0, 0);
    await button('添加节点').hover();
    await tooltip.waitFor();
    assert.match(await tooltip.innerText(), /添加节点/);
    await page.waitForTimeout(100);
    const hint = await tooltip.boundingBox();
    await page.mouse.move(hint.x + hint.width / 2, hint.y + hint.height / 2, { steps: 5 });
    await page.waitForTimeout(500);
    assert.equal(await tooltip.isVisible(), true);
    await page.keyboard.press('Escape');
    await tooltip.waitFor({ state: 'hidden' });
    await button('保存草稿').scrollIntoViewIfNeeded();
    await button('保存草稿').evaluate(el => el.blur());
    await button('保存草稿').focus();
    await tooltip.waitFor();
    assert.match(await tooltip.innerText(), /保存草稿/);
    await page.locator('.wf-header').screenshot({ path: output + `header-hint-${mode}.png` });
    await page.keyboard.press('Escape');
    await tooltip.waitFor({ state: 'hidden' });
  }
  checks.push('11 icon-only controls retain accessible names and shared 34×34 sizing in dark/light', 'Hints open on hover/focus, stay readable when hovered, dismiss with Escape');
  await theme('dark');
  await button('添加节点').click();
  await page.getByRole('heading', { name: '节点库', exact: true }).waitFor();
  await page.getByLabel('搜索节点类型', { exact: true }).fill('转换');
  await page.locator('.wf-left').getByRole('button', { name: /字段与单位转换/ }).click();
  assert.equal(await page.locator('.wf-node').count(), 12);
  await button('撤销').click();
  assert.equal(await page.locator('.wf-node').count(), 11);
  await button('重做').click();
  assert.equal(await page.locator('.wf-node').count(), 12);
  await button('撤销').click();
  if (await button('关闭配置').isVisible()) await button('关闭配置').click();
  await button('流程大纲').click();
  await page.getByRole('heading', { name: '流程大纲', exact: true }).waitFor();
  assert.equal(await page.locator('.wf-node-list button').count(), 11);
  await page.getByRole('tab', { name: /^连接 / }).click();
  await page.getByRole('combobox', { name: '来源节点', exact: true }).waitFor();
  await button('添加节点').focus();
  await tooltip.waitFor();
  await page.keyboard.press('Escape');
  await tooltip.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('heading', { name: '流程大纲', exact: true }).isVisible(), true);
  await button('关闭侧栏').click();
  checks.push('Library adds templates; outline lists 11 existing nodes and their connections; add/undo/redo remain functional; tooltip Escape preserves open drawer');
  await button('保存草稿').click();
  await page.waitForFunction(() => document.querySelector('.wf-identity')?.textContent.includes('已保存'));
  assert.ok(await page.evaluate(() => localStorage.getItem('immortal-workflow-demo-draft-v2')));
  await button('测试流程').click();
  await button('停止等待').waitFor();
  assert.equal(await button('停止等待').innerText(), '');
  await button('停止等待').waitFor({ state: 'hidden' });
  assert.match(await page.locator('.wf-console').innerText(), /20 ≥ 21：未命中/);
  checks.push('Icon save persists the draft; icon test transitions to stop and produces actual demo run records');
  await button('展开工作区').click();
  await button('保存草稿').focus();
  await tooltip.waitFor();
  assert.equal(await tooltip.evaluate(el => !!el.closest('dialog[open]')), true);
  await page.keyboard.press('Escape');
  await tooltip.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('dialog').isVisible(), true);
  await button('更多流程操作').click();
  await page.getByRole('menuitem', { name: '流程设置', exact: true }).click();
  await page.getByLabel('流程名称', { exact: true }).waitFor();
  await button('关闭配置').click();
  await button('收起工作区').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await button('保存草稿').focus();
  await tooltip.waitFor();
  assert.equal(await tooltip.evaluate(el => !!el.closest('.wf-root')), true);
  await page.keyboard.press('Escape');
  checks.push('Hints and menu work in expanded native dialog; Escape dismisses the hint without closing the workspace');
  const initialTransform = await page.locator('.react-flow__viewport').getAttribute('style');
  await button('放大画布').click();
  assert.notEqual(await page.locator('.react-flow__viewport').getAttribute('style'), initialTransform);
  await button('显示完整流程').click();
  await button('缩小画布').click();
  checks.push('Zoom and fit keep separate behavior from workspace expansion');
  for (const mode of ['dark', 'light']) {
    await page.setViewportSize({ width: 320, height: 900 });
    await theme(mode, 20);
    await button('保存草稿').scrollIntoViewIfNeeded();
    await button('保存草稿').evaluate(el => el.blur());
    await button('保存草稿').focus();
    await tooltip.waitFor();
    const bounds = await tooltip.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 320);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 320);
    assert.equal(await page.locator('.react-flow__minimap').isVisible(), false);
    await page.screenshot({ path: output + `narrow-${mode}.png` });
    await page.keyboard.press('Escape');
  }
  checks.push('320px viewport with 20px font: no document overflow and hints remain within the viewport');
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await context.newPage();
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(base);
  await mobile.locator('.wf-node').first().waitFor();
  measurements.touch = await mobile.locator(toolSelector).evaluateAll(buttons => buttons.map(b => ({ name: b.ariaLabel, width: b.getBoundingClientRect().width, height: b.getBoundingClientRect().height })));
  assert.ok(measurements.touch.every(b => b.width >= 40 && b.height >= 40));
  const add = mobile.getByRole('button', { name: '添加节点', exact: true });
  await add.scrollIntoViewIfNeeded();
  const rect = await add.boundingBox(), cdp = await context.newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: rect.x + rect.width / 2, y: rect.y + rect.height / 2 }] });
  await mobile.waitForTimeout(600);
  await mobile.locator('.wf-tooltip').waitFor();
  assert.equal(await mobile.getByRole('heading', { name: '节点库', exact: true }).count(), 0);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await mobile.waitForTimeout(200);
  assert.equal(await mobile.getByRole('heading', { name: '节点库', exact: true }).count(), 0);
  await mobile.screenshot({ path: output + 'touch-hint.png' });
  await add.tap();
  await mobile.getByRole('heading', { name: '节点库', exact: true }).waitFor();
  await mobile.getByRole('button', { name: '更多流程操作', exact: true }).tap();
  await mobile.getByRole('menuitem', { name: '流程设置', exact: true }).waitFor();
  await context.close();
  checks.push('Touch: all 11 controls ≥40×40; long-press shows label without activating; subsequent tap opens library; more menu exposes text');
  assert.deepEqual(errors, []);
  await writeFile(output + 'checks.json', JSON.stringify({ browser: browser.version(), checks, measurements, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: output + 'failure.png', fullPage: true });
  throw error;
} finally {
  await browser.close();
}
